/** Resolves and applies per-role models on managed DSH sessions without mutating the global DSH default. */
import type { Context } from '@deepseek-ai/cordis'
import type { Agent, ModelSelection } from '@deepseek-ai/dsh-agent'
import { boundContextSummary, createUserMessage, ReasoningEffortId } from '@deepseek-ai/dsh-llm'
import type { RoleModel } from '../policy.ts'

interface RoleModelOverride {
  active?: ModelSelection
  assembled?: ModelSelection
  appending: boolean
}

const overrides = new WeakMap<Agent, RoleModelOverride>()

function sameRoute(left: Pick<ModelSelection, 'provider' | 'model'>, right: Pick<ModelSelection, 'provider' | 'model'>): boolean {
  return left.provider === right.provider && left.model === right.model
}

function routeLabel(route: Pick<ModelSelection, 'provider' | 'model'>, other: Pick<ModelSelection, 'provider' | 'model'>): string {
  return route.provider === other.provider ? route.model : `${route.provider}/${route.model}`
}

function modelSwitchNotice(previous: Pick<ModelSelection, 'provider' | 'model'>, selected: Pick<ModelSelection, 'provider' | 'model'>) {
  const from = routeLabel(previous, selected), to = routeLabel(selected, previous)
  return createUserMessage({
    content: [{ type: 'text', text: `[model changed: assistant turns above this point were generated by ${from}; the session continues with ${to}]` }],
    source: { kind: 'model-selection', form: 'notice', summary: boundContextSummary(`${from} → ${to}`) },
  })
}

function ensureOverride(ctx: Context, agent: Agent): RoleModelOverride {
  const existing = overrides.get(agent)
  if (existing) return existing
  const state: RoleModelOverride = { appending: false }
  overrides.set(agent, state)
  agent.ctx.effect(() => {
    const disposers = [
      agent.ctx.on('system-prompt/assemble', async (_assembly, _context, next) => {
        const selection = state.active
        const result = await next()
        state.assembled = selection
        return selection ? { ...result, variables: { ...result.variables, provider: selection.provider, model: selection.model } } : result
      }, { prepend: true }),
      agent.ctx.on('agent/request', async (_payload, next) => {
        const result = await next()
        if (!state.assembled) return result
        const { reasoningEffort: _inherited, ...rest } = result
        return { ...rest, ...state.assembled }
      }, { prepend: true }),
      agent.ctx.on('agent/pre-step', async ({ agent: stepAgent, messages, signal, step }, next) => {
        const decision = await next()
        if (decision.kind === 'reject' || signal.aborted) return decision
        if (decision.messages.length === 0 && (step === 1 || messages.length > 0)) return decision
        const selected = state.assembled
        if (!selected) return decision
        const filtered = decision.messages.filter(message => message.source?.kind !== 'model-selection')
        const previous = stepAgent.session.requestHeader()?.config
        if (!previous || sameRoute(previous, selected)) {
          return filtered.length === decision.messages.length ? decision : { ...decision, messages: filtered }
        }
        return { ...decision, messages: [...filtered, modelSwitchNotice(previous, selected)] }
      }, { prepend: true }),
      ctx.on('session/event', (session, event) => {
        // Yield to any later manual model switch (e.g. from DSH's chat selector).
        if (session === agent.session && event.type === 'model/selection' && !state.appending) state.active = undefined
      }),
    ]
    return () => {
      overrides.delete(agent)
      disposers.forEach(dispose => dispose())
    }
  })
  return state
}

async function resolveDefaultRoleModel(ctx: Context): Promise<ModelSelection | undefined> {
  const defaultService = (ctx as { agentDefaultModel?: { currentSelection?: () => ModelSelection | undefined } }).agentDefaultModel
  const current = defaultService?.currentSelection?.()
  if (current) return resolveRoleModel(ctx, current)
  const controller = ctx.sessionController as { modelCatalog?: () => Promise<{ default: RoleModel | null }> } | undefined
  const catalog = typeof controller?.modelCatalog === 'function' ? await controller.modelCatalog().catch(() => undefined) : undefined
  return catalog?.default ? resolveRoleModel(ctx, catalog.default) : undefined
}

async function applySelection(ctx: Context, agent: Agent, selected: ModelSelection): Promise<void> {
  const state = ensureOverride(ctx, agent)
  // Avoid selectModel because it mutates the global DSH default; record the durable selection and override prompt/request routing for this session.
  state.active = selected
  try {
    state.appending = true
    agent.session.append('model/selection', selected)
  } finally {
    state.appending = false
  }
  await ctx.sessionPersistence.flush()
}

/** Resolve a configured route through the live provider; catalog membership is not a restriction. */
export async function resolveRoleModel(ctx: Context, model: RoleModel): Promise<ModelSelection> {
  const value = await ctx.llm.resolveCallConfig({ provider: model.provider, model: model.model,
    ...(model.reasoningEffort ? { reasoningEffort: ReasoningEffortId(model.reasoningEffort) } : {}) })
  return { provider: value.provider, model: value.model, ...(value.reasoningEffort ? { reasoningEffort: value.reasoningEffort } : {}) }
}

/** Seed a role's configured model onto a brand-new session before its first request, leaving later manual or durable selections intact. */
export async function initializeRoleModel(ctx: Context, agent: Agent, model: RoleModel | null): Promise<void> {
  if (!model) return
  if (agent.session.requestHeader() || agent.session.snapshotEvents().some(event => event.type === 'model/selection')) return
  const selected = await resolveRoleModel(ctx, model)
  await applySelection(ctx, agent, selected)
}

/** Switch an existing session to a newly saved role model (or the current DSH default when `null`) for its next request without mutating DSH's global default. */
export async function applyRoleModel(ctx: Context, agent: Agent, model: RoleModel | null, resolved?: ModelSelection): Promise<boolean> {
  const selected = model ? (resolved ?? await resolveRoleModel(ctx, model)) : await resolveDefaultRoleModel(ctx)
  if (!selected) return false
  await applySelection(ctx, agent, selected)
  return true
}
